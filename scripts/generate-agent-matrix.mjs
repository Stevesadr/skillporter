#!/usr/bin/env node
/**
 * Generate `docs/agents.md` from the capability profiles in `agents/`.
 *
 * The profiles are the source of truth. This script reads them through the same
 * loader the CLI uses, so the document cannot describe a profile that the tool
 * would reject. `--check` fails when the committed document has drifted.
 *
 * Usage:
 *   node scripts/generate-agent-matrix.mjs           # write the document
 *   node scripts/generate-agent-matrix.mjs --check   # fail if it is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'docs', 'agents.md');
const CORE = join(ROOT, 'packages', 'core', 'dist', 'index.js');

const { loadProfiles } = await import(`file://${CORE}`);
const profiles = [...(await loadProfiles())].sort((a, b) => a.id.localeCompare(b.id));

function cell(text) {
  return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function table(rows, headers) {
  const lines = [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`];
  for (const row of rows) lines.push(`| ${row.map(cell).join(' | ')} |`);
  return lines.join('\n');
}

function yesNo(value) {
  if (value === true) return 'yes';
  if (value === false) return 'no';
  return 'unknown';
}

function roots(entries) {
  if (entries.length === 0) return '—';
  return entries.map((entry) => `\`${entry.path}\``).join('<br>');
}

function nameRule(profile) {
  const parts = [];
  parts.push(profile.name.pattern === null ? 'no grammar' : `\`${profile.name.pattern}\``);
  if (profile.name.maxLength !== null) parts.push(`≤ ${profile.name.maxLength}`);
  if ((profile.name.reserved ?? []).length > 0) parts.push(`reserved: ${profile.name.reserved.map((word) => `\`${word}\``).join(', ')}`);
  if (profile.name.enforcement === 'unknown') parts.push('enforcement unknown');
  else if (profile.name.enforcement !== 'none') parts.push(`(${profile.name.enforcement})`);
  return parts.join(' · ');
}

function descriptionRule(profile) {
  const parts = [];
  parts.push(profile.description.maxLength === null ? 'no limit' : `≤ ${profile.description.maxLength}`);
  if (profile.description.enforcement === 'unknown') parts.push('enforcement unknown');
  else if (profile.description.enforcement !== 'none') parts.push(`(${profile.description.enforcement})`);
  const truncation = profile.description.truncation;
  if (truncation) parts.push(`display truncation at ${truncation.at} ${truncation.unit}`);
  return parts.join(' · ');
}

function shell(profile) {
  const executed = profile.bodyExecution.shellInjection.executed;
  if (executed === 'unknown') return 'unknown';
  return executed ? 'yes' : 'no';
}

function delivery(profile) {
  return profile.delivery === 'archive' ? 'uploaded bundle' : 'directory';
}

/**
 * How a user invokes a skill, with the skill's own name in place of `{name}`.
 *
 * `unknown` is printed rather than left blank: a blank cell reads as "not
 * applicable", and this column is exactly where the difference matters.
 */
function invocation(profile) {
  const syntax = profile.invocation?.syntax;
  if (syntax === undefined || syntax === 'unknown') return 'unknown';
  return `\`${syntax.split('{name}').join('name')}\``;
}

const lines = [];
lines.push('# Supported agents');
lines.push('');
lines.push(
  '> Generated from `agents/*.yaml` by `scripts/generate-agent-matrix.mjs`.',
  '> Do not edit this file by hand: edit the profile and regenerate.',
);
lines.push('');
lines.push(
  `${profiles.length} capability profiles. A profile is data, not code: adding an agent means adding one`,
  'YAML file and citing a source for every fact in it. No command in the tool names an agent.',
);
lines.push('');
lines.push(
  '`verified` means every fact traces to a primary source retrieved on the date shown. `partial` means some',
  'facts are documented and at least one is not. `unverified` means the profile exists but nothing in it was',
  'confirmed. An unknown fact is never guessed: it is written as `unknown` and reported as a warning.',
);
lines.push('');

// ---- at a glance ----------------------------------------------------------
lines.push('## At a glance');
lines.push('');
lines.push(
  table(
    profiles.map((profile) => [
      profile.displayName,
      `\`${profile.id}\``,
      delivery(profile),
      roots(profile.paths.project),
      roots(profile.paths.global),
      profile.identity.source,
      nameRule(profile),
      descriptionRule(profile),
      shell(profile),
      invocation(profile),
      profile.verification,
    ]),
    ['Agent', 'id', 'Delivery', 'Project roots', 'Global roots', 'Identity from', 'Name', 'Description', 'Executes body shell', 'Invoke as', 'Verified'],
  ),
);
lines.push('');
lines.push(
  'A project root is relative to the project. A global root is under the user home. `directory` means the agent',
  'discovers a folder on disk; `uploaded bundle` means the skill is uploaded and has no discovery root, so',
  '`convert --install` refuses it and `--out` writes the folder to upload instead.',
);
lines.push('');
lines.push(
  '"Invoke as" is how a user starts a skill from the chat prompt, with the skill name written as `name`. `unknown`',
  'means the agent documents no per-skill command, and no lint rule may then claim a reference is wrong.',
);
lines.push('');

// ---- frontmatter fields ---------------------------------------------------
const FIELD_ORDER = ['name', 'description', 'license', 'compatibility', 'metadata', 'allowed-tools'];
const seen = new Set(FIELD_ORDER);
for (const profile of profiles) for (const key of Object.keys(profile.fields)) seen.add(key);
const fieldKeys = [...seen].sort((a, b) => {
  const left = FIELD_ORDER.indexOf(a);
  const right = FIELD_ORDER.indexOf(b);
  if (left !== -1 && right !== -1) return left - right;
  if (left !== -1) return -1;
  if (right !== -1) return 1;
  return a.localeCompare(b);
});

lines.push('## Frontmatter fields');
lines.push('');
lines.push(
  table(
    fieldKeys.map((key) => [
      `\`${key}\``,
      ...profiles.map((profile) => {
        const field = profile.fields[key];
        if (field === undefined) return '—';
        return field.dropReason === undefined ? field.status : `${field.status} (dropped)`;
      }),
    ]),
    ['Field', ...profiles.map((profile) => profile.displayName)],
  ),
);
lines.push('');
lines.push(
  '`supported` is carried over as written. `emulated` is rewritten into something the agent does act on.',
  '`ignored` and `unsupported` are reported as losses. `unknown` is kept verbatim and reported as a warning,',
  'unless the profile also records a `dropReason`, in which case the field is dropped rather than guessed at.',
  'A dash means the profile does not mention the field at all.',
);
lines.push('');

// ---- discovery ------------------------------------------------------------
lines.push('## Discovery');
lines.push('');
lines.push(
  table(
    profiles
      .filter((profile) => delivery(profile) === 'directory')
      .map((profile) => [
        profile.displayName,
        String(profile.discovery.skillDirDepth),
        yesNo(profile.discovery.acceptsFlatMarkdown),
        yesNo(profile.discovery.followsSymlinks),
        yesNo(profile.discovery.upwardSearch),
        profile.discovery.nestedLazyLoad === undefined ? '—' : yesNo(profile.discovery.nestedLazyLoad),
        profile.discovery.duplicateResolution ?? '—',
      ]),
    ['Agent', 'Skill dir depth', 'Flat `.md`', 'Follows symlinks', 'Upward search', 'Lazy nested load', 'Duplicate resolution'],
  ),
);
lines.push('');

// ---- what is unknown ------------------------------------------------------
const unknowns = [];
for (const profile of profiles) {
  for (const [key, field] of Object.entries(profile.fields)) {
    if (field.dropReason !== undefined) unknowns.push([profile.displayName, `\`${key}\``, field.dropReason]);
  }
}
if (unknowns.length > 0) {
  lines.push('## Fields dropped rather than guessed');
  lines.push('');
  lines.push(
    'The target\'s acceptance of these fields is undocumented. Emitting one would be a guess, so the field is',
    'dropped and the loss is reported with this reason.',
  );
  lines.push('');
  lines.push(table(unknowns, ['Agent', 'Field', 'Why it is dropped']));
  lines.push('');
}

// ---- notes ----------------------------------------------------------------
const notes = profiles.filter((profile) => typeof profile.notes === 'string' && profile.notes.length > 0);
if (notes.length > 0) {
  lines.push('## Profile notes');
  lines.push('');
  for (const profile of notes) {
    lines.push(`- **${profile.displayName}** — ${profile.notes}`);
  }
  lines.push('');
}

// ---- sources --------------------------------------------------------------
lines.push('## Sources');
lines.push('');
const sourceRows = [];
for (const profile of profiles) {
  for (const source of profile.sources) {
    sourceRows.push([
      profile.displayName,
      source.url,
      source.retrieved,
      (source.covers ?? []).join(', ') || '—',
      source.note ?? '',
    ]);
  }
}
lines.push(table(sourceRows, ['Agent', 'URL', 'Retrieved', 'Covers', 'Note']));
lines.push('');

const document = lines.join('\n');

if (process.argv.includes('--check')) {
  const existing = await readFile(OUT, 'utf8').catch(() => null);
  if (existing === null) {
    console.error('docs/agents.md is missing. Run: node scripts/generate-agent-matrix.mjs');
    process.exit(1);
  }
  if (existing !== document) {
    console.error('docs/agents.md is out of date. Run: node scripts/generate-agent-matrix.mjs');
    process.exit(1);
  }
  console.log('docs/agents.md is up to date.');
} else {
  await writeFile(OUT, document);
  console.log(`wrote docs/agents.md (${profiles.length} profiles)`);
}
