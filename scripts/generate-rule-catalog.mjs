#!/usr/bin/env node
/**
 * Generate `docs/lint-rules.md` from the rule catalogue in code.
 *
 * The catalogue is the source of truth: this script never invents a rule, and
 * `--check` fails if the committed document has drifted from it.
 *
 * Usage:
 *   node scripts/generate-rule-catalog.mjs           # write the document
 *   node scripts/generate-rule-catalog.mjs --check   # fail if it is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'docs', 'lint-rules.md');
const RULES_MODULE = join(ROOT, 'packages', 'core', 'dist', 'rules.js');

const { LINT_RULES, rulesByDiagnosticCode } = await import(`file://${RULES_MODULE}`);

const AREA_ORDER = ['format', 'paths', 'discovery', 'identity', 'name', 'description', 'fields', 'bodyExecution'];

const AREA_TITLE = {
  format: 'File format and layout',
  paths: 'Paths and discovery roots',
  discovery: 'Discovery rules',
  identity: 'Identity',
  name: 'Name',
  description: 'Description',
  fields: 'Frontmatter fields',
  bodyExecution: 'Body execution',
};

function cell(text) {
  return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function table(rows, headers) {
  const lines = [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`];
  for (const row of rows) lines.push(`| ${row.map(cell).join(' | ')} |`);
  return lines.join('\n');
}

function render() {
  const lines = [];
  const profileRules = LINT_RULES.filter((rule) => rule.derivation === 'profile');
  const toolRules = LINT_RULES.filter((rule) => rule.derivation === 'tool');

  lines.push('# Lint rules');
  lines.push('');
  lines.push(
    '> Generated from `packages/core/src/rules.ts` by `scripts/generate-rule-catalog.mjs`.',
    '> Do not edit this file by hand: edit the catalogue and regenerate.',
  );
  lines.push('');
  lines.push(
    `${LINT_RULES.length} rules: ${profileRules.length} derived from capability-profile data and ${toolRules.length} that report`,
    'skillporter\'s own observations. No rule names an agent. Every rule id is stable:',
    'it is never reused and never renumbered, so a report can be diffed across releases.',
  );
  lines.push('');
  lines.push('## How severity is decided');
  lines.push('');
  lines.push(
    'Severity is a function of what the agent *does*, read from the target capability profile. The rule is:',
  );
  lines.push('');
  lines.push('| The agent… | Profile value | Severity |');
  lines.push('| --- | --- | --- |');
  lines.push('| refuses to load the skill | `enforcement: reject` | `error` |');
  lines.push('| drops it from the catalog silently | `enforcement: silent-skip` | `error` |');
  lines.push('| shortens a display string | `enforcement: truncate` | `warning` |');
  lines.push('| ignores the field | `fields[].status: ignored` | `warning` |');
  lines.push('| does not enforce anything | `enforcement: none` | `info` |');
  lines.push('| behaviour is undocumented | `unknown`, `null` | `warning` |');
  lines.push('');
  lines.push(
    '`silent-skip` counts as an error even though nothing is visibly rejected: the outcome is the same for the',
    'user, because the skill never appears and the only feedback is a log line. Anything undocumented is a',
    'warning rather than an error, because the project reports gaps instead of guessing at them.',
  );
  lines.push('');
  lines.push('## Rules');
  lines.push('');

  for (const area of AREA_ORDER) {
    const group = LINT_RULES.filter((rule) => rule.area === area);
    if (group.length === 0) continue;

    lines.push(`### ${AREA_TITLE[area] ?? area}`);
    lines.push('');
    lines.push(
      table(
        group.map((rule) => [
          `\`${rule.id}\``,
          rule.title,
          `\`${rule.slug}\``,
          rule.derivation === 'tool' ? 'tool' : `\`${rule.derivedFrom}\``,
          `\`${rule.code}\``,
          rule.severityPolicy,
        ]),
        ['ID', 'Rule', 'Slug', 'Derived from', 'Code', 'Severity'],
      ),
    );
    lines.push('');
    for (const rule of group) {
      lines.push(`- **${rule.id}** — ${rule.description}`);
      lines.push(`  Fix: ${rule.fix}`);
    }
    lines.push('');
  }

  lines.push('## Diagnostic code to rule id');
  lines.push('');
  lines.push(
    'Diagnostic codes are the parser\'s stable vocabulary. Several rules can emit the same code, and the same',
    'fact can produce a different severity per target agent, so the rule id is the finer-grained identifier:',
    '`code` says what kind of fact was observed, `ruleId` says what it means for this target.',
  );
  lines.push('');
  const mapping = rulesByDiagnosticCode();
  const codes = [...mapping.keys()].sort();
  lines.push(
    table(
      codes.map((code) => {
        const rules = mapping.get(code) ?? [];
        return [`\`${code}\``, rules.map((rule) => `\`${rule.id}\``).join(', ')];
      }),
      ['Diagnostic code', 'Rules'],
    ),
  );
  lines.push('');
  lines.push('## Suppression');
  lines.push('');
  lines.push(
    '`--ignore-unknown` suppresses findings whose diagnostic code is `UNKNOWN_CAPABILITY`, which is what every',
    '"we have no verified answer" finding carries: SP011, SP012, SP013, SP015, and SP017 when the target\'s',
    'shell behaviour is undocumented. It never suppresses an error, and never suppresses a verified fact.',
  );
  lines.push('');
  lines.push('## Exit codes');
  lines.push('');
  lines.push('| Code | Meaning |');
  lines.push('| --- | --- |');
  lines.push('| `0` | clean, or informational findings only |');
  lines.push('| `1` | at least one `error` |');
  lines.push('| `2` | no errors, at least one `warning` |');
  lines.push('');
  lines.push(
    '`--ignore-unknown` can turn a `2` into a `0`, never a `1` into a `0`.',
  );
  lines.push('');

  return lines.join('\n');
}

const document = render();

if (process.argv.includes('--check')) {
  const existing = await readFile(OUT, 'utf8').catch(() => null);
  if (existing === null) {
    console.error('docs/lint-rules.md is missing. Run: node scripts/generate-rule-catalog.mjs');
    process.exit(1);
  }
  if (existing !== document) {
    console.error('docs/lint-rules.md is out of date. Run: node scripts/generate-rule-catalog.mjs');
    process.exit(1);
  }
  console.log('docs/lint-rules.md is up to date.');
} else {
  await writeFile(OUT, document);
  console.log(`wrote docs/lint-rules.md (${LINT_RULES.length} rules)`);
}
